# -*- coding: utf-8 -*-
"""扩语料：从标准库 + site-packages 构建更大的字符级语料。

与 prepare_data.py 的区别：
  - 不止标准库，还收 site-packages（torch / numpy / pandas / sklearn ...）
  - 多道质量过滤，避免把「数据文件」和「自动生成代码」混进来
  - 单包限流，防止 torch 一家占据三成语料
  - 输出到 corpus_big.txt / vocab_big.json，不覆盖现有语料

用法：
    python src/prepare_data_big.py                 # 默认 2000 万字符
    python src/prepare_data_big.py --target-mb 20
"""

import os
import sys
import json
import random
import hashlib
import argparse
import sysconfig

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from config import Config

# ---------------------------------------------------------------- 过滤规则

# 目录名黑名单：测试代码冗长重复；_inductor/_dynamo 里嵌着 C++ 模板字符串；
# lexers 是语法高亮的正则字典（是数据不是代码）；vendor 是第三方副本。
EXCLUDE_DIRS = {
    "test", "tests", "__pycache__", "idlelib", "lib2to3", "turtledemo",
    "distutils", "site-packages",
    "_inductor", "_dynamo", "_functorch", "_C", "include",
    "lexers", "vendor", "vendored", "_vendor", "third_party",
}

# 文件内容里的生成标记：自动生成的代码不是人写的，学了没用
GENERATED_MARKERS = (
    "auto-generated", "autogenerated", "@generated", "do not edit",
    "this file is generated", "generated by the protocol buffer",
    "machine generated",
)

MIN_FILE_BYTES = 800        # 太小的文件大多是 __init__ 转发，信息密度低
PER_PACKAGE_CAP = 0.15      # 单个包最多贡献目标的 15%


def is_generated(text: str) -> bool:
    head = text[:1200].lower()
    return any(m in head for m in GENERATED_MARKERS)


def clean_lines(text: str) -> str:
    """只保留纯 ASCII 行。

    为什么这么做：Python 源码 98.8% 是 ASCII，剩下 1.2% 是 docstring 里的
    emoji、重音字母、装饰符号。这些字符种类高达 4,682 种，会把词表
    （96 个位置）挤爆，导致 ^ 和 & 这类真正的运算符落榜。

    实测代价：丢 1.2% 字符，换来字符种类 4682 → 96，词表零丢弃。
    """
    return "\n".join(l for l in text.split("\n") if l.isascii())


def collect_from(root: str, exclude_dirs=None, ascii_only=True):
    """遍历目录，返回 [(路径, 文本)]，已做目录过滤与内容去重。"""
    exclude_dirs = exclude_dirs or EXCLUDE_DIRS
    seen_hash = set()
    out = []
    for r, dirs, names in os.walk(root):
        dirs[:] = sorted(d for d in dirs
                         if d not in exclude_dirs and not d.startswith("."))
        for name in sorted(names):
            if not name.endswith(".py"):
                continue
            p = os.path.join(r, name)
            try:
                if os.path.getsize(p) < MIN_FILE_BYTES:
                    continue
                text = open(p, encoding="utf-8", errors="ignore").read()
            except OSError:
                continue
            if is_generated(text):
                continue
            if ascii_only:
                text = clean_lines(text)
            if len(text) < MIN_FILE_BYTES:
                continue
            # 内容去重：很多包会 vendor 同一份 compat.py / six.py
            h = hashlib.md5(text.encode("utf-8", "ignore")).hexdigest()
            if h in seen_hash:
                continue
            seen_hash.add(h)
            out.append((p, text))
    return out


def group_by_package(files, root):
    """按顶层目录（即包名）分组，用于单包限流。"""
    groups = {}
    for p, t in files:
        rel = os.path.relpath(p, root)
        pkg = rel.split(os.sep)[0] if os.sep in rel else "(root)"
        groups.setdefault(pkg, []).append((p, t))
    return groups


def build_vocab(text: str, vocab_size: int):
    freq = {}
    for ch in text:
        freq[ch] = freq.get(ch, 0) + 1
    ordered = sorted(freq.items(), key=lambda kv: -kv[1])
    chars = [c for c, _ in ordered[:vocab_size]]
    itos = {i: c for i, c in enumerate(chars)}
    stoi = {c: i for i, c in itos.items()}
    return itos, stoi


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--target-mb", type=float, default=20.0,
                    help="目标语料大小（MB），默认 20")
    ap.add_argument("--out", default="data/corpus_big.txt")
    ap.add_argument("--vocab-out", default="data/vocab_big.json")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--keep-unicode", action="store_true",
                    help="保留含非 ASCII 字符的行（默认丢弃，避免 emoji 挤占词表）")
    args = ap.parse_args()
    ascii_only = not args.keep_unicode

    cfg = Config()
    base = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    os.chdir(base)

    target = int(args.target_mb * 1024 * 1024)
    rng = random.Random(args.seed)

    # ---------------- 收集 ----------------
    pools = []

    stdlib = sysconfig.get_paths()["stdlib"]
    print("标准库  :", stdlib)
    std_files = collect_from(stdlib, ascii_only=ascii_only)
    print("  %d 个文件可用，%.2f MB" % (len(std_files),
                                      sum(len(t) for _, t in std_files) / 1e6))
    pools.append(("stdlib", std_files, 0.25))   # 标准库最多占 25%

    sp = os.path.join(base, ".venv", "Lib", "site-packages")
    if not os.path.isdir(sp):
        sp = sysconfig.get_paths()["purelib"]
    print("site-packages:", sp)
    sp_files = collect_from(sp, ascii_only=ascii_only)
    print("  %d 个文件可用，%.2f MB" % (len(sp_files),
                                      sum(len(t) for _, t in sp_files) / 1e6))

    # ---------------- 单包限流 ----------------
    groups = group_by_package(sp_files, sp)
    cap = int(target * PER_PACKAGE_CAP)
    print("\n单包上限 %.0f 万字符（%.0f%%），共有 %d 个包："
          % (cap / 1e4, PER_PACKAGE_CAP * 100, len(groups)))

    kept = []
    for pkg, items in sorted(groups.items(), key=lambda kv: -sum(len(t) for _, t in kv[1])):
        rng.shuffle(items)
        acc = 0
        take = []
        for p, t in items:
            if acc + len(t) > cap:
                continue
            take.append((p, t))
            acc += len(t)
        kept.extend(take)
        if acc > 200_000:
            print("  %-24s %6.2f MB  %3d 文件%s"
                  % (pkg, acc / 1e6, len(take),
                     "  (已限流)" if acc >= cap * 0.95 else ""))

    # ---------------- 拼装 ----------------
    rng.shuffle(std_files)
    rng.shuffle(kept)
    std_cap = int(target * 0.25)

    chunks, total = [], 0
    for p, t in std_files:
        if total + len(t) > std_cap:
            continue
        chunks.append(t)
        total += len(t)
    std_bytes = total

    for p, t in kept:
        if total + len(t) > target:
            continue
        chunks.append(t)
        total += len(t)

    rng.shuffle(chunks)
    text = "\n\n".join(chunks)

    print("\n拼装完成: %s 字符 (%.2f MB)" % (format(len(text), ","), len(text) / 1e6))
    print("  标准库 %5.2f MB / site-packages %5.2f MB"
          % (std_bytes / 1e6, (len(text) - std_bytes) / 1e6))

    # ---------------- 词表 ----------------
    itos, stoi = build_vocab(text, cfg.vocab_size)
    covered = sum(1 for ch in text if ch in stoi)
    print("\n词表大小: %d" % len(itos))
    print("字符覆盖率: %.4f%%" % (100 * covered / len(text)))
    print("被丢弃的字符（前 12 个）: %s"
          % " ".join(repr(c) for c in sorted(set(text) - set(stoi),
                                             key=lambda c: -text.count(c))[:12]))

    os.makedirs("data", exist_ok=True)
    with open(args.out, "w", encoding="utf-8") as f:
        f.write(text)
    with open(args.vocab_out, "w", encoding="utf-8") as f:
        json.dump({"itos": {str(k): v for k, v in itos.items()}}, f,
                  ensure_ascii=False, indent=1)

    print("\n已写入:")
    print("  %s (%.2f MB)" % (args.out, os.path.getsize(args.out) / 1e6))
    print("  %s" % args.vocab_out)
    print("\n下一步:")
    print("  python src/train.py --corpus %s --vocab %s --ckpt results/model_big.pt"
          % (args.out, args.vocab_out))


if __name__ == "__main__":
    main()
